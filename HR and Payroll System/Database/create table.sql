--------------------------------------------------------
-- HR and Payroll System - Database Setup Scripts
--------------------------------------------------------

-- 1. Departments Table
CREATE TABLE DEPARTMENTS (
    Department_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Department_Name VARCHAR2(100) NOT NULL
);

-- 2. Employees Table
CREATE TABLE EMPLOYEES (
    Employee_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    First_Name VARCHAR2(50) NOT NULL,
    Last_Name VARCHAR2(50) NOT NULL,
    Email VARCHAR2(100),
    Phone_Number VARCHAR2(20),
    Hire_Date DATE,
    Department_ID NUMBER,
    CONSTRAINT fk_emp_dept FOREIGN KEY (Department_ID) REFERENCES DEPARTMENTS(Department_ID)
);

-- 3. Attendance Table
CREATE TABLE ATTENDANCE (
    Attendance_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Employee_ID NUMBER,
    Attendance_Date DATE,
    Status VARCHAR2(20), -- Present, Absent, Leave
    CONSTRAINT fk_att_emp FOREIGN KEY (Employee_ID) REFERENCES EMPLOYEES(Employee_ID)
);

-- 4. Leave Records Table
CREATE TABLE LEAVE_RECORDS (
    Leave_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Employee_ID NUMBER,
    Start_Date DATE,
    End_Date DATE,
    Leave_Type VARCHAR2(50),
    Status VARCHAR2(20), -- Approved, Pending, Rejected
    CONSTRAINT fk_leave_emp FOREIGN KEY (Employee_ID) REFERENCES EMPLOYEES(Employee_ID)
);

-- 5. Salary Table
CREATE TABLE SALARY (
    Salary_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Employee_ID NUMBER,
    Basic_Salary NUMBER(10,2),
    House_Rent NUMBER(10,2) DEFAULT 0,
    Medical_Allowance NUMBER(10,2) DEFAULT 0,
    CONSTRAINT fk_salary_emp FOREIGN KEY (Employee_ID) REFERENCES EMPLOYEES(Employee_ID)
);

-- 6. Overtime Table
CREATE TABLE OVERTIME (
    Overtime_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Employee_ID NUMBER,
    Overtime_Date DATE,
    Hours_Worked NUMBER(5,2),
    Hourly_Rate NUMBER(10,2),
    CONSTRAINT fk_ot_emp FOREIGN KEY (Employee_ID) REFERENCES EMPLOYEES(Employee_ID)
);

-- 7. Payroll Table
CREATE TABLE PAYROLL (
    Payroll_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Employee_ID NUMBER,
    Payroll_Month VARCHAR2(20),
    Gross_Salary NUMBER(10,2),
    Total_Deductions NUMBER(10,2) DEFAULT 0,
    Net_Salary NUMBER(10,2),
    Payment_Date DATE,
    Payment_Status VARCHAR2(20), -- Paid, Pending
    CONSTRAINT fk_payroll_emp FOREIGN KEY (Employee_ID) REFERENCES EMPLOYEES(Employee_ID)
);

-- 8. Products Table (Inventory Section)
CREATE TABLE PRODUCTS (
    Product_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Product_Name VARCHAR2(100) NOT NULL,
    Category VARCHAR2(50),
    Unit_Price NUMBER(10,2),
    Description VARCHAR2(255)
);

-- 9. Stock Inventory Table (Inventory Section)
CREATE TABLE STOCK_INVENTORY (
    Stock_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Product_ID NUMBER,
    Quantity NUMBER,
    Stock_Date DATE,
    Stock_Type VARCHAR2(50), -- In, Out
    Supplier VARCHAR2(100),
    CONSTRAINT fk_stock_prod FOREIGN KEY (Product_ID) REFERENCES PRODUCTS(Product_ID)
);

-- 10. Available Stock Table (Inventory Section)
CREATE TABLE AVAILABLE_STOCK (
    Available_Stock_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Product_ID NUMBER,
    Available_Quantity NUMBER,
    Last_Updated DATE,
    CONSTRAINT fk_avail_prod FOREIGN KEY (Product_ID) REFERENCES PRODUCTS(Product_ID)
);